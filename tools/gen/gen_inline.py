#!/usr/bin/env python3
"""Generate a GCC-15-clean inline header for bsdsocket.library calls from
the NDK's inline/bsdsocket.h (whose void functions list scratch registers
both as inputs and clobbers, which current GCC rejects).

Scratch registers (d0/d1/a0/a1) are always asm operands: "+r" when they
carry an argument, "=r" otherwise, so nothing needs to be clobbered.

Output: build/gen/bsdsocket_inline.h
Usage:  python -I tools/gen/gen_inline.py
"""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
TOP = os.path.dirname(os.path.dirname(HERE))
sys.path.insert(0, HERE)
import parse_inline  # noqa: E402

INLINE = os.path.join(TOP, "toolchain", "opt", "m68k-amiga-elf",
                      "sys-include", "inline", "bsdsocket.h")
OUT = os.path.join(TOP, "build", "gen", "bsdsocket_inline.h")
SCRATCH = ("d0", "d1", "a0", "a1")


def main():
    lines = ["/* generated by tools/gen/gen_inline.py -- do not edit */",
             "#ifndef AMIBSDNET_BSDSOCKET_INLINE_H",
             "#define AMIBSDNET_BSDSOCKET_INLINE_H",
             "#ifndef BSDSOCKET_BASE_NAME",
             "#define BSDSOCKET_BASE_NAME SocketBase",
             "#endif", ""]
    for name, off, ret, args in parse_inline.parse(INLINE):
        params = [(t, a, r) for t, a, r in args if r != "a6"]
        pnames = ", ".join(a for t, a, r in params)
        body = [f"#define {name}({pnames}) ({{ \\"]
        for t, a, r in params:
            body.append(f"  {t} _{name}_{a} = ({a}); \\")
        body.append("  register struct Library * const __bn __asm(\"a6\") = "
                    "(struct Library *)(BSDSOCKET_BASE_NAME); \\")
        outs, ins = [], ['"r"(__bn)']
        used = {}
        for t, a, r in params:
            used[r] = (t, a)
        for r in SCRATCH:
            if r in used:
                t, a = used[r]
                body.append(f"  register {t} __{r} __asm(\"{r}\") = "
                            f"_{name}_{a}; \\")
                outs.append(f'"+r"(__{r})')
            else:
                body.append(f"  register ULONG __{r} __asm(\"{r}\"); \\")
                outs.append(f'"=r"(__{r})')
        for t, a, r in params:
            if r in SCRATCH:
                continue
            body.append(f"  register {t} __{r} __asm(\"{r}\") = "
                        f"_{name}_{a}; \\")
            ins.append(f'"r"(__{r})')
        body.append(f"  __asm volatile (\"jsr -{off}(%%a6)\" \\")
        body.append(f"    : {', '.join(outs)} \\")
        body.append(f"    : {', '.join(ins)} \\")
        body.append("    : \"fp0\", \"fp1\", \"cc\", \"memory\"); \\")
        if ret == "void":
            body.append("  (void)0; \\")
        else:
            body.append(f"  ({ret})__d0; \\")
        body.append("})")
        lines += body + [""]
    lines.append("#endif")
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    open(OUT, "w", newline="\n").write("\n".join(lines) + "\n")
    print(f"gen_inline: {OUT}")


if __name__ == "__main__":
    main()
