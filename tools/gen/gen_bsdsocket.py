#!/usr/bin/env python3
"""Generate the bsdsocket.library jump table and register glue from the
NDK inline header (the authoritative source for LVO offsets and argument
registers of the AmiTCP/Roadshow API).

Output:
  build/gen/bsdsocket_vec.s   vector table + one stub per function
  build/gen/bsdsocket_proto.h prototypes of the sb_<name>() C functions

Each stub pushes the register arguments in C order (plus the library base
from A6 first) and calls sb_<name>().  Functions without an sb_<name>
implementation, and reserved slots, go to sb_unimplemented (returns -1
with errno ENOSYS).  The list of implemented functions is read from
src/lib/*.c: any definition named sb_<name>( counts.

Usage: python -I tools/gen/gen_bsdsocket.py
"""
import glob
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
TOP = os.path.dirname(os.path.dirname(HERE))
sys.path.insert(0, HERE)
import parse_inline  # noqa: E402

INLINE = os.path.join(TOP, "toolchain", "opt", "m68k-amiga-elf",
                      "sys-include", "inline", "bsdsocket.h")
OUT = os.path.join(TOP, "build", "gen")


def implemented():
    names = set()
    for p in glob.glob(os.path.join(TOP, "src", "lib", "*.c")):
        for m in re.finditer(r"^sb_(\w+)\(", open(p).read(), re.M):
            names.add(m.group(1))
    return names


def main():
    funcs = parse_inline.parse(INLINE)
    impl = implemented()
    last = max(f[1] for f in funcs)
    byoff = {f[1]: f for f in funcs}
    os.makedirs(OUT, exist_ok=True)

    s = ["| generated by tools/gen/gen_bsdsocket.py -- do not edit",
         "\t.text", "\t.globl\tbsdsocket_vectors", "\t.even",
         "bsdsocket_vectors:",
         "\t.long\tsb_lib_open_stub", "\t.long\tsb_lib_close_stub",
         "\t.long\tsb_lib_expunge_stub", "\t.long\tsb_lib_null"]
    for off in range(30, last + 6, 6):
        f = byoff.get(off)
        if f and f[0] in impl:
            s.append(f"\t.long\tsbv_{f[0]}")
        else:
            s.append("\t.long\tsb_unimplemented_stub")
    s.append("\t.long\t-1")

    # library housekeeping vectors (A6 = base)
    s += ["sb_lib_open_stub:", "\tmove.l\t%d0,-(%sp)", "\tmove.l\t%a6,-(%sp)",
          "\tjsr\tsb_lib_open", "\taddq.l\t#8,%sp", "\trts",
          "sb_lib_close_stub:", "\tmove.l\t%a6,-(%sp)", "\tjsr\tsb_lib_close",
          "\taddq.l\t#4,%sp", "\trts",
          "sb_lib_expunge_stub:", "\tmove.l\t%a6,-(%sp)",
          "\tjsr\tsb_lib_expunge", "\taddq.l\t#4,%sp", "\trts",
          "sb_lib_null:", "\tmoveq\t#0,%d0", "\trts",
          "sb_unimplemented_stub:", "\tmove.l\t%a6,-(%sp)",
          "\tjsr\tsb_unimplemented", "\taddq.l\t#4,%sp", "\trts"]

    protos = ["/* generated by tools/gen/gen_bsdsocket.py -- do not edit */",
              "#ifndef BSDSOCKET_PROTO_H", "#define BSDSOCKET_PROTO_H",
              "struct SocketBase;"]
    for name, off, ret, args in funcs:
        if name not in impl:
            continue
        regs = [r for t, a, r in args if r != "a6"]
        s.append(f"sbv_{name}:")
        for r in reversed(regs):
            s.append(f"\tmove.l\t%{r},-(%sp)")
        s.append("\tmove.l\t%a6,-(%sp)")
        s.append(f"\tjsr\tsb_{name}")
        s.append(f"\tlea\t{4 * (len(regs) + 1)}(%sp),%sp")
        s.append("\trts")
        cargs = ", ".join(["struct SocketBase *"] +
                          [t for t, a, r in args if r != "a6"])
        protos.append(f"{ret} sb_{name}({cargs});")
    protos.append("#endif")

    open(os.path.join(OUT, "bsdsocket_vec.s"), "w", newline="\n").write(
        "\n".join(s) + "\n")
    open(os.path.join(OUT, "bsdsocket_proto.h"), "w", newline="\n").write(
        "\n".join(protos) + "\n")
    missing = sorted(f[0] for f in funcs if f[0] not in impl)
    print(f"gen_bsdsocket: {len(funcs)} functions, {len(funcs) - len(missing)} "
          f"implemented, {len(missing)} -> ENOSYS")
    if "-v" in sys.argv:
        print("  unimplemented: " + " ".join(missing))


if __name__ == "__main__":
    main()
